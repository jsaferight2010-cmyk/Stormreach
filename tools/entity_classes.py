"""Maps every vanilla entity type (EntityTypes field name) to its Java class, read from the 26.3 jar's bytecode.
In 26.x EntityType.getBaseClass() always returns Entity.class, so Storm mobs need this table to find the class
to clone. Writes src/main/resources/stormreach_entity_classes.txt. Needs `javap` and the Minecraft jar
(STORMREACH_MCJAR, default /home/claude/mc/mc65.jar)."""
import os, re, subprocess, tempfile, zipfile, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
jar = os.environ.get('STORMREACH_MCJAR', '/home/claude/mc/mc65.jar')
with tempfile.TemporaryDirectory() as d:
    p = os.path.join(d, 'EntityTypes.class')
    open(p, 'wb').write(zipfile.ZipFile(jar).read('net/minecraft/world/entity/EntityTypes.class'))
    t = subprocess.run(['javap', '-c', '-p', '-v', p], capture_output=True, text=True).stdout
bsec = t[t.index('BootstrapMethods:'):]
bs = {}
for m in re.finditer(r'^\s+(\d+): #\d+ REF_invokeStatic[^\n]*\n\s+Method arguments:\n((?:\s+#\d+[^\n]*\n)+)', bsec, re.M):
    args = m.group(2)
    h = re.search(r'REF_newInvokeSpecial ([\w/$]+)\."<init>"', args)
    if h: bs[int(m.group(1))] = ('new', h.group(1)); continue
    h = re.search(r'REF_invokeStatic net/minecraft/world/entity/EntityTypes\.(lambda\$[\w$]+):', args)
    if h: bs[int(m.group(1))] = ('lambda', h.group(1))
def lambda_new(name):
    i = t.find(' ' + name + '(')
    if i < 0: return None
    m = re.search(r'new\s+#\d+\s+// class ([\w/$]+)', t[i:t.find('\n\n', i)])
    return m.group(1) if m else None
st = t[t.index('static {};'):t.index('BootstrapMethods:')]
out, cur = {}, None
for l in st.split('\n'):
    m = re.search(r'getstatic .*EntityTypeIds\.(\w+):', l)
    if m: cur = m.group(1); continue
    m = re.search(r'InvokeDynamic #(\d+):create:\(\)Lnet/minecraft/world/entity/EntityType\$EntityFactory', l)
    if m and cur and cur not in out and int(m.group(1)) in bs:
        k, v = bs[int(m.group(1))]
        c = v if k == 'new' else lambda_new(v)
        if c: out[cur] = c.replace('/', '.')
(ROOT / 'src/main/resources/stormreach_entity_classes.txt').write_text(
    '# EntityTypes field = entity class (generated by tools/entity_classes.py from the 26.3 jar)\n' + ''.join(f'{k}={v}\n' for k, v in sorted(out.items())))
print(len(out), 'entity classes mapped')
