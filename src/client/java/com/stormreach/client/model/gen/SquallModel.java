    @Override
    public void setupAnim(RigState s) {
        super.setupAnim(s);
        float t = s.ageInTicks;
        float moveW = Rig.ease(Math.min(1f, s.walkAnimationSpeed * 2.2f)), idleW = 1f - moveW;
        float air = s.air, ground = 1f - air, swim = s.isInWater ? 1f : 0f, dry = 1f - swim;
        float turn = Mth.clamp(s.turn, -12f, 12f);
        { float w = 1f; float ph = t / 40f + s.seed;
          if (w > 0.002f) {
            core.y += Keys.loop(K1, ph) * w;
            { float d = Keys.loop(K2, ph) * w; core.xScale += d; core.yScale += d; core.zScale += d; }
            wisp0.zRot += Rig.DEG * Keys.loop(K3, ph) * w;
            wisp1.xRot += Rig.DEG * Keys.loop(K4, ph) * w;
            wisp1.zRot += Rig.DEG * Keys.loop(K5, ph) * w;
            wisp2.zRot += Rig.DEG * Keys.loop(K6, ph) * w;
            wisp3.zRot += Rig.DEG * Keys.loop(K7, ph) * w;
        } }
        { float ph = Rig.pulse(s.attackAge, 15f);
          if (ph >= 0 && s.attackKind == AnimPulse.ATTACK) {
            core.z += Keys.once(K8, ph) * 1f;
            core.xScale += Keys.once(K9, ph) * 1f;
            core.zScale += Keys.once(K10, ph) * 1f;
            ring0.yRot += Rig.DEG * Keys.once(K11, ph) * 1f;
            ring1.yRot += Rig.DEG * Keys.once(K12, ph) * 1f;
            wisp0.xRot += Rig.DEG * Keys.once(K13, ph) * 1f;
            wisp1.xRot += Rig.DEG * Keys.once(K14, ph) * 1f;
        } }
        { float ph = Rig.pulse(s.hurtAge, 10f);
          if (ph >= 0) {
            core.zRot += Rig.DEG * Keys.once(K15, ph) * 1f;
            { float d = Keys.once(K16, ph) * 1f; core.xScale += d; core.yScale += d; core.zScale += d; }
        } }
        ring0.yRot += t * 0.3f;
        ring1.yRot -= t * 0.22f;
        ring2.yRot += t * 0.4f;
        wisp0.zRot -= turn * 0.04f;

    }
