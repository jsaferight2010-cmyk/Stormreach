/**
 * The Stormfly: a firefly whose tail glows with stored lightning, on two buzzing wings under raised wing cases.
 * Generated by tools/mobmodels.py (texture textures/entity/stormfly.png, 64x32 units at 4x). Don't edit.
 */
@SuppressWarnings("unused")
public class StormflyModel extends EntityModel<RigState> {
    private static final float[] K1 = {0f, -50f, 0.5f, 40f};
    private static final float[] K2 = {0f, 50f, 0.5f, -40f};
    private static final float[] K3 = {0f, 0f, 0.25f, -0.6f, 0.5f, 0f, 0.75f, 0.6f};
    private static final float[] K4 = {0f, -10f, 0.5f, -4f};
    private static final float[] K5 = {0f, 6f, 0.5f, -6f};
    private static final float[] K6 = {0f, -6f, 0.5f, 6f};
    private static final float[] K7 = {0f, 0f, 0.12f, 0.4f, 0.5f, -0.1f, 1f, 0f};
    private static final float[] K8 = {0f, 0f, 0.15f, -6f, 0.4f, 2f, 0.7f, -1f, 1f, 0f};

    final ModelPart body;
    final ModelPart head;
    final ModelPart leftAntenna;
    final ModelPart rightAntenna;
    final ModelPart leftWing;
    final ModelPart rightWing;
    final ModelPart leftElytron;
    final ModelPart rightElytron;

    public StormflyModel(ModelPart root) {
        super(root, net.minecraft.client.renderer.rendertype.RenderTypes::entityTranslucent);
        body = root.getChild("body");
        head = root.getChild("body").getChild("head");
        leftAntenna = root.getChild("body").getChild("head").getChild("left_antenna");
        rightAntenna = root.getChild("body").getChild("head").getChild("right_antenna");
        leftWing = root.getChild("body").getChild("left_wing");
        rightWing = root.getChild("body").getChild("right_wing");
        leftElytron = root.getChild("body").getChild("left_elytron");
        rightElytron = root.getChild("body").getChild("right_elytron");
    }

    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition p1 = root.addOrReplaceChild("body", CubeListBuilder.create().texOffs(0, 0).addBox(-1f, -1f, -1.5f, 2, 2, 3).texOffs(30, 0).addBox(-0.8f, -0.8f, 1.2f, 2, 2, 2), PartPose.offset(0f, 20f, 0f));
        PartDefinition p2 = p1.addOrReplaceChild("head", CubeListBuilder.create().texOffs(38, 0).addBox(-1f, -1f, -1.5f, 2, 2, 2).texOffs(20, 5).addBox(-1.2f, -0.8f, -1.4f, 1, 1, 1).texOffs(24, 5).addBox(0.6f, -0.8f, -1.4f, 1, 1, 1), PartPose.offset(0f, 0f, -1.5f));
        PartDefinition p3 = p2.addOrReplaceChild("left_antenna", CubeListBuilder.create().texOffs(12, 5).addBox(-0.5f, -2f, -0.5f, 1, 2, 1), PartPose.offsetAndRotation(0.5f, -1f, -1.2f, -0.7f, 0f, 0.4f));
        PartDefinition p4 = p2.addOrReplaceChild("right_antenna", CubeListBuilder.create().texOffs(16, 5).mirror().addBox(-0.5f, -2f, -0.5f, 1, 2, 1).mirror(false), PartPose.offsetAndRotation(-0.5f, -1f, -1.2f, -0.7f, 0f, -0.4f));
        PartDefinition p5 = p1.addOrReplaceChild("left_wing", CubeListBuilder.create().texOffs(46, 0).addBox(0f, -0.5f, -1f, 4, 1, 2), PartPose.offsetAndRotation(0.6f, -1f, -0.5f, 0f, 0.25f, 0f));
        PartDefinition p6 = p1.addOrReplaceChild("right_wing", CubeListBuilder.create().texOffs(0, 5).mirror().addBox(-4f, -0.5f, -1f, 4, 1, 2).mirror(false), PartPose.offsetAndRotation(-0.6f, -1f, -0.5f, 0f, -0.25f, 0f));
        PartDefinition p7 = p1.addOrReplaceChild("left_elytron", CubeListBuilder.create().texOffs(10, 0).addBox(0f, -0.5f, 0f, 2, 1, 3), PartPose.offsetAndRotation(0.5f, -1f, -1f, 0f, -0.2f, -0.35f));
        PartDefinition p8 = p1.addOrReplaceChild("right_elytron", CubeListBuilder.create().texOffs(20, 0).mirror().addBox(-2f, -0.5f, 0f, 2, 1, 3).mirror(false), PartPose.offsetAndRotation(-0.5f, -1f, -1f, 0f, 0.2f, 0.35f));
        return LayerDefinition.create(mesh, 64, 32);
    }

    @Override
    public void setupAnim(RigState s) {
        super.setupAnim(s);
        float t = s.ageInTicks;
        float moveW = Rig.ease(Math.min(1f, s.walkAnimationSpeed * 2.2f)), idleW = 1f - moveW;
        float air = s.air, ground = 1f - air, swim = s.isInWater ? 1f : 0f, dry = 1f - swim;
        float turn = Mth.clamp(s.turn, -12f, 12f);
        { float w = 1f; float ph = t / 2f + s.seed;
          if (w > 0.002f) {
            leftWing.zRot += Rig.DEG * Keys.loop(K1, ph) * w;
            rightWing.zRot += Rig.DEG * Keys.loop(K2, ph) * w;
        } }
        { float w = 1f; float ph = t / 30f + s.seed;
          if (w > 0.002f) {
            body.y += Keys.loop(K3, ph) * w;
            body.xRot += Rig.DEG * Keys.loop(K4, ph) * w;
            leftAntenna.zRot += Rig.DEG * Keys.loop(K5, ph) * w;
            rightAntenna.zRot += Rig.DEG * Keys.loop(K6, ph) * w;
        } }
        { float ph = Rig.pulse(s.hurtAge, 10f);
          if (ph >= 0) {
            body.z += Keys.once(K7, ph) * 1f;
            body.xRot += Rig.DEG * Keys.once(K8, ph) * 1f;
        } }

    }
}
