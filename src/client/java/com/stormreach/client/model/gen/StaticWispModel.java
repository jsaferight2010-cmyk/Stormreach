/**
 * The Static Wisp: a crackling golden spark with a crown of spikes and a trailing tail.
 * Generated by tools/mobmodels.py (texture textures/entity/static_wisp.png, 64x32 units at 4x). Don't edit.
 */
@SuppressWarnings("unused")
public class StaticWispModel extends EntityModel<LivingEntityRenderState> {
    final ModelPart core;
    final ModelPart trail0;
    final ModelPart trail1;

    public StaticWispModel(ModelPart root) {
        super(root);
        core = root.getChild("core");
        trail0 = root.getChild("core").getChild("trail_0");
        trail1 = root.getChild("core").getChild("trail_0").getChild("trail_1");
    }

    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition p1 = root.addOrReplaceChild("core", CubeListBuilder.create().texOffs(0, 0).addBox(-2.5f, -2.5f, -2.5f, 5, 5, 5).texOffs(0, 10).addBox(-1.5f, -1f, -2.8f, 1, 1, 1).texOffs(4, 10).addBox(0.5f, -1f, -2.8f, 1, 1, 1), PartPose.offset(0f, 14f, 0f));
        PartDefinition p2 = p1.addOrReplaceChild("spike_0", CubeListBuilder.create().texOffs(32, 0).addBox(-0.5f, -4f, -0.5f, 1, 4, 1), PartPose.offsetAndRotation(2.5f, -2.5f, 0f, 0f, 0f, -0.5f));
        PartDefinition p3 = p1.addOrReplaceChild("spike_1", CubeListBuilder.create().texOffs(36, 0).addBox(-0.5f, -4f, -0.5f, 1, 4, 1), PartPose.offsetAndRotation(0.7725f, -2.5f, 2.3776f, 0.4755f, 0f, -0.1545f));
        PartDefinition p4 = p1.addOrReplaceChild("spike_2", CubeListBuilder.create().texOffs(40, 0).addBox(-0.5f, -4f, -0.5f, 1, 4, 1), PartPose.offsetAndRotation(-2.0225f, -2.5f, 1.4695f, 0.2939f, 0f, 0.4045f));
        PartDefinition p5 = p1.addOrReplaceChild("spike_3", CubeListBuilder.create().texOffs(44, 0).addBox(-0.5f, -4f, -0.5f, 1, 4, 1), PartPose.offsetAndRotation(-2.0225f, -2.5f, -1.4695f, -0.2939f, 0f, 0.4045f));
        PartDefinition p6 = p1.addOrReplaceChild("spike_4", CubeListBuilder.create().texOffs(48, 0).addBox(-0.5f, -4f, -0.5f, 1, 4, 1), PartPose.offsetAndRotation(0.7725f, -2.5f, -2.3776f, -0.4755f, 0f, -0.1545f));
        PartDefinition p7 = p1.addOrReplaceChild("trail_0", CubeListBuilder.create().texOffs(20, 0).addBox(-1.5f, 0f, -1.5f, 3, 3, 3), PartPose.offset(0f, 2.5f, 0f));
        PartDefinition p8 = p7.addOrReplaceChild("trail_1", CubeListBuilder.create().texOffs(52, 0).addBox(-1f, 0f, -1f, 2, 3, 2), PartPose.offset(0f, 3f, 0f));
        PartDefinition p9 = p8.addOrReplaceChild("trail_2", CubeListBuilder.create().texOffs(60, 0).addBox(-0.5f, 0f, -0.5f, 1, 3, 1), PartPose.offset(0f, 3f, 0f));
        return LayerDefinition.create(mesh, 64, 32);
    }

    @Override
    public void setupAnim(LivingEntityRenderState s) {
        super.setupAnim(s);
        float t = s.ageInTicks, walk = s.walkAnimationPos * 0.6662f, amt = Math.min(1f, s.walkAnimationSpeed);
        core.y = 14f + Mth.sin(t * 0.2f) * 1.5f;
        core.yRot = t * 0.15f;
        trail0.xRot = Mth.sin(t * 0.3f) * 0.3f;
        trail1.zRot = Mth.cos(t * 0.35f) * 0.35f;
    }
}
