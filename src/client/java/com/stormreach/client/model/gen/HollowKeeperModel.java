            leftFore.xRot += Rig.DEG * Keys.loop(K7, ph) * w;
            rightArm.xRot += Rig.DEG * Keys.loop(K8, ph) * w;
            rightFinger0.xRot += Rig.DEG * Keys.loop(K9, ph) * w;
            rightFore.xRot += Rig.DEG * Keys.loop(K10, ph) * w;
