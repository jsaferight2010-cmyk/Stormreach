package com.stormreach.client.model.gen;

import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.client.renderer.entity.state.LivingEntityRenderState;
import net.minecraft.util.Mth;

/**
 * The Harbor Seal: a round two-part body that wiggles, whiskered snout, front flippers and a tail fluke.
 * Generated by tools/mobmodels.py (texture textures/entity/harbor_seal.png, 64x32 units at 4x). Don't edit.
 */
@SuppressWarnings("unused")
public class HarborSealModel extends EntityModel<LivingEntityRenderState> {
    final ModelPart body;
    final ModelPart rear;
    final ModelPart tail;
    final ModelPart head;
    final ModelPart leftFlipper;
    final ModelPart rightFlipper;

    public HarborSealModel(ModelPart root) {
        super(root);
        body = root.getChild("body");
        rear = root.getChild("body").getChild("rear");
        tail = root.getChild("body").getChild("rear").getChild("tail");
        head = root.getChild("body").getChild("head");
        leftFlipper = root.getChild("body").getChild("left_flipper");
        rightFlipper = root.getChild("body").getChild("right_flipper");
    }

    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition p1 = root.addOrReplaceChild("body", CubeListBuilder.create().texOffs(0, 0).addBox(-4f, -3f, -6f, 8, 6, 8).texOffs(22, 14).addBox(-3.5f, 2.5f, -5.5f, 7, 1, 7), PartPose.offset(0f, 20f, 0f));
        PartDefinition p2 = p1.addOrReplaceChild("rear", CubeListBuilder.create().texOffs(32, 0).addBox(-3f, -2.5f, 0f, 6, 5, 6), PartPose.offset(0f, 0f, 2f));
        PartDefinition p3 = p2.addOrReplaceChild("tail", CubeListBuilder.create().texOffs(0, 24).addBox(-3f, -0.5f, 0f, 6, 1, 3), PartPose.offset(0f, 0.5f, 6f));
        PartDefinition p4 = p1.addOrReplaceChild("head", CubeListBuilder.create().texOffs(0, 14).addBox(-3f, -3f, -4f, 6, 5, 5).texOffs(18, 24).addBox(-1.5f, -1f, -6f, 3, 2, 2).texOffs(56, 24).addBox(-3.5f, -1f, -5.5f, 1, 1, 1).texOffs(60, 24).addBox(2.5f, -1f, -5.5f, 1, 1, 1), PartPose.offset(0f, -2f, -6f));
        PartDefinition p5 = p4.addOrReplaceChild("left_eye", CubeListBuilder.create().texOffs(0, 28).addBox(-0.5f, -0.5f, -0.5f, 1, 1, 1), PartPose.offset(2f, -2f, -4f));
        PartDefinition p6 = p4.addOrReplaceChild("right_eye", CubeListBuilder.create().texOffs(4, 28).addBox(-0.5f, -0.5f, -0.5f, 1, 1, 1), PartPose.offset(-2f, -2f, -4f));
        PartDefinition p7 = p1.addOrReplaceChild("left_flipper", CubeListBuilder.create().texOffs(28, 24).addBox(0f, -0.5f, -1.5f, 4, 1, 3), PartPose.offsetAndRotation(4f, 2f, -3f, 0f, 0f, 0.6f));
        PartDefinition p8 = p1.addOrReplaceChild("right_flipper", CubeListBuilder.create().texOffs(42, 24).mirror().addBox(-4f, -0.5f, -1.5f, 4, 1, 3).mirror(false), PartPose.offsetAndRotation(-4f, 2f, -3f, 0f, 0f, -0.6f));
        return LayerDefinition.create(mesh, 64, 32);
    }

    @Override
    public void setupAnim(LivingEntityRenderState s) {
        super.setupAnim(s);
        float t = s.ageInTicks, walk = s.walkAnimationPos * 0.6662f, amt = Math.min(1f, s.walkAnimationSpeed);
        rear.yRot = Mth.sin(walk * 1.5f) * 0.25f * amt + Mth.sin(t * 0.05f) * 0.05f;
        tail.xRot = Mth.sin(t * 0.15f) * 0.2f;
        leftFlipper.zRot = 0.6f + Mth.sin(walk * 2f) * 0.5f * amt;
        rightFlipper.zRot = -0.6f - Mth.sin(walk * 2f) * 0.5f * amt;
        head.yRot = s.yRot * Mth.DEG_TO_RAD;
        head.xRot = s.xRot * Mth.DEG_TO_RAD;
    }
}
