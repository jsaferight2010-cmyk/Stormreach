    @Override
    public void setupAnim(RigState s) {
        super.setupAnim(s);
        float t = s.ageInTicks;
        float moveW = Rig.ease(Math.min(1f, s.walkAnimationSpeed * 2.2f)), idleW = 1f - moveW;
        float air = s.air, ground = 1f - air, swim = s.isInWater ? 1f : 0f, dry = 1f - swim;
        float turn = Mth.clamp(s.turn, -12f, 12f);
        { float w = idleW; float ph = t / 60f + s.seed;
          if (w > 0.002f) {
            body.y += Keys.loop(K1, ph) * w;
            tail1.yRot += Rig.DEG * Keys.loop(K2, ph) * w;
            tail2.yRot += Rig.DEG * Keys.loop(K3, ph) * w;
            tail3.yRot += Rig.DEG * Keys.loop(K4, ph) * w;
        } }
        { float w = moveW; float ph = s.walkAnimationPos * 0.32f;
          if (w > 0.002f) {
            body.yRot += Rig.DEG * Keys.loop(K5, ph) * w;
            head.yRot += Rig.DEG * Keys.loop(K6, ph) * w;
            leftBack.yRot += Rig.DEG * Keys.loop(K7, ph) * w;
            leftBack.zRot += Rig.DEG * Keys.loop(K8, ph) * w;
            leftFront.yRot += Rig.DEG * Keys.loop(K9, ph) * w;
            leftFront.zRot += Rig.DEG * Keys.loop(K10, ph) * w;
            rightBack.yRot += Rig.DEG * Keys.loop(K11, ph) * w;
            rightBack.zRot += Rig.DEG * Keys.loop(K12, ph) * w;
            rightFront.yRot += Rig.DEG * Keys.loop(K13, ph) * w;
            rightFront.zRot += Rig.DEG * Keys.loop(K14, ph) * w;
            tail0.yRot += Rig.DEG * Keys.loop(K15, ph) * w;
            tail1.yRot += Rig.DEG * Keys.loop(K16, ph) * w;
            tail2.yRot += Rig.DEG * Keys.loop(K17, ph) * w;
        } }
        { float w = idleW; float ph = Rig.fidget(t, s.seed, 130f, 22f);
          if (ph >= 0 && w > 0.002f) {
            body.y += Keys.once(K18, ph) * w;
            head.xRot += Rig.DEG * Keys.once(K19, ph) * w;
        } }
        { float w = idleW; float ph = Rig.fidget(t, s.seed, 45f, 14f);
          if (ph >= 0 && w > 0.002f) {
            head.yRot += Rig.DEG * Keys.once(K20, ph) * w;
        } }
        { float w = idleW; float ph = Rig.fidget(t, s.seed, 70f, 8f);
          if (ph >= 0 && w > 0.002f) {
            jaw.xRot += Rig.DEG * Keys.once(K21, ph) * w;
        } }
        { float ph = Rig.pulse(s.hurtAge, 10f);
          if (ph >= 0) {
            body.z += Keys.once(K22, ph) * 1f;
            body.xRot += Rig.DEG * Keys.once(K23, ph) * 1f;
            head.xRot += Rig.DEG * Keys.once(K24, ph) * 1f;
            head.zRot += Rig.DEG * Keys.once(K25, ph) * 1f;
        } }
        head.yRot += s.yRot * Rig.DEG * 1f; head.xRot += s.xRot * Rig.DEG * 0.8f;
        for (ModelPart p : new ModelPart[] {spark0, spark1, spark2, spark3, spark4}) p.visible = s.charged;
        tail0.yRot += turn * 0.05f;

    }
