    @Override
    public void setupAnim(RigState s) {
        super.setupAnim(s);
        float t = s.ageInTicks;
        float moveW = Rig.ease(Math.min(1f, s.walkAnimationSpeed * 2.2f)), idleW = 1f - moveW;
        float air = s.air, ground = 1f - air, swim = s.isInWater ? 1f : 0f, dry = 1f - swim;
        float turn = Mth.clamp(s.turn, -12f, 12f);
        { float w = 1f; float ph = t / 90f + s.seed;
          if (w > 0.002f) {
            body.y += Keys.loop(K1, ph) * w;
            body.xRot += Rig.DEG * Keys.loop(K2, ph) * w;
            head.xRot += Rig.DEG * Keys.loop(K3, ph) * w;
            jaw.xRot += Rig.DEG * Keys.loop(K4, ph) * w;
            leftFin.zRot += Rig.DEG * Keys.loop(K5, ph) * w;
            leftFinTip.zRot += Rig.DEG * Keys.loop(K6, ph) * w;
            rightFin.zRot += Rig.DEG * Keys.loop(K7, ph) * w;
            rightFinTip.zRot += Rig.DEG * Keys.loop(K8, ph) * w;
            tail.xRot += Rig.DEG * Keys.loop(K9, ph) * w;
            tailEnd.xRot += Rig.DEG * Keys.loop(K10, ph) * w;
            tailMid.xRot += Rig.DEG * Keys.loop(K11, ph) * w;
        } }
        { float w = 1f; float ph = Rig.fidget(t, s.seed, 420f, 90f);
          if (ph >= 0 && w > 0.002f) {
            head.xRot += Rig.DEG * Keys.once(K12, ph) * w;
            jaw.xRot += Rig.DEG * Keys.once(K13, ph) * w;
        } }
        { float ph = Rig.pulse(s.hurtAge, 10f);
          if (ph >= 0) {
            body.z += Keys.once(K14, ph) * 1f;
            body.xRot += Rig.DEG * Keys.once(K15, ph) * 1f;
            head.xRot += Rig.DEG * Keys.once(K16, ph) * 1f;
            head.zRot += Rig.DEG * Keys.once(K17, ph) * 1f;
        } }
        tail.yRot += turn * 0.05f; tailMid.yRot += turn * 0.04f;

    }
