package com.stormreach.client.model.gen;

import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.client.renderer.entity.state.LivingEntityRenderState;
import net.minecraft.util.Mth;

/**
 * The Storm Gull: a grey-backed gull with two-jointed wings, a fanned tail and webbed feet.
 * Generated by tools/mobmodels.py (texture textures/entity/storm_gull.png, 64x32 units at 4x). Don't edit.
 */
@SuppressWarnings("unused")
public class StormGullModel extends EntityModel<LivingEntityRenderState> {
    final ModelPart body;
    final ModelPart head;
    final ModelPart leftWing;
    final ModelPart leftWingtip;
    final ModelPart rightWing;
    final ModelPart rightWingtip;
    final ModelPart tail;
    final ModelPart leftLeg;
    final ModelPart rightLeg;

    public StormGullModel(ModelPart root) {
        super(root);
        body = root.getChild("body");
        head = root.getChild("body").getChild("head");
        leftWing = root.getChild("body").getChild("left_wing");
        leftWingtip = root.getChild("body").getChild("left_wing").getChild("left_wingtip");
        rightWing = root.getChild("body").getChild("right_wing");
        rightWingtip = root.getChild("body").getChild("right_wing").getChild("right_wingtip");
        tail = root.getChild("body").getChild("tail");
        leftLeg = root.getChild("body").getChild("left_leg");
        rightLeg = root.getChild("body").getChild("right_leg");
    }

    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition p1 = root.addOrReplaceChild("body", CubeListBuilder.create().texOffs(0, 0).addBox(-2f, -2f, -4f, 4, 4, 8).texOffs(22, 12).addBox(-1.5f, 1f, -3f, 3, 1, 5), PartPose.offset(0f, 18f, 0f));
        PartDefinition p2 = p1.addOrReplaceChild("head", CubeListBuilder.create().texOffs(38, 12).addBox(-1.5f, -3f, -3f, 3, 3, 3), PartPose.offset(0f, -2f, -4f));
        PartDefinition p3 = p2.addOrReplaceChild("beak", CubeListBuilder.create().texOffs(4, 25).addBox(-0.5f, -0.5f, -2.5f, 1, 1, 2), PartPose.offset(0f, -1.5f, -3f));
        PartDefinition p4 = p2.addOrReplaceChild("left_eye", CubeListBuilder.create().texOffs(26, 25).addBox(0f, -0.5f, -0.5f, 1, 1, 1), PartPose.offset(1.5f, -2f, -2f));
        PartDefinition p5 = p2.addOrReplaceChild("right_eye", CubeListBuilder.create().texOffs(30, 25).addBox(-1f, -0.5f, -0.5f, 1, 1, 1), PartPose.offset(-1.5f, -2f, -2f));
        PartDefinition p6 = p1.addOrReplaceChild("left_wing", CubeListBuilder.create().texOffs(24, 0).addBox(0f, 0f, 0f, 5, 1, 6), PartPose.offset(2f, -1.5f, -2f));
        PartDefinition p7 = p6.addOrReplaceChild("left_wingtip", CubeListBuilder.create().texOffs(0, 19).addBox(0f, 0f, 0f, 6, 1, 5), PartPose.offset(5f, 0f, 0f));
        PartDefinition p8 = p1.addOrReplaceChild("right_wing", CubeListBuilder.create().texOffs(0, 12).mirror().addBox(-5f, 0f, 0f, 5, 1, 6).mirror(false), PartPose.offset(-2f, -1.5f, -2f));
        PartDefinition p9 = p8.addOrReplaceChild("right_wingtip", CubeListBuilder.create().texOffs(22, 19).mirror().addBox(-6f, 0f, 0f, 6, 1, 5).mirror(false), PartPose.offset(-5f, 0f, 0f));
        PartDefinition p10 = p1.addOrReplaceChild("tail", CubeListBuilder.create().texOffs(44, 19).addBox(-2f, 0f, 0f, 4, 1, 4), PartPose.offsetAndRotation(0f, -1f, 4f, -0.2f, 0f, 0f));
        PartDefinition p11 = p1.addOrReplaceChild("left_leg", CubeListBuilder.create().texOffs(60, 19).addBox(-0.5f, 0f, -0.5f, 1, 3, 1).texOffs(10, 25).addBox(-1f, 3f, -1.5f, 2, 1, 2), PartPose.offset(1f, 2f, 1f));
        PartDefinition p12 = p1.addOrReplaceChild("right_leg", CubeListBuilder.create().texOffs(0, 25).mirror().addBox(-0.5f, 0f, -0.5f, 1, 3, 1).mirror(false).texOffs(18, 25).mirror().addBox(-1f, 3f, -1.5f, 2, 1, 2).mirror(false), PartPose.offset(-1f, 2f, 1f));
        return LayerDefinition.create(mesh, 64, 32);
    }

    @Override
    public void setupAnim(LivingEntityRenderState s) {
        super.setupAnim(s);
        float t = s.ageInTicks, walk = s.walkAnimationPos * 0.6662f, amt = Math.min(1f, s.walkAnimationSpeed);
        float flap = Mth.sin(t * 0.45f);
        leftWing.zRot = -0.15f + flap * 0.7f;
        rightWing.zRot = 0.15f - flap * 0.7f;
        leftWingtip.zRot = flap * 0.4f;
        rightWingtip.zRot = -flap * 0.4f;
        head.yRot = s.yRot * Mth.DEG_TO_RAD;
        head.xRot = s.xRot * Mth.DEG_TO_RAD;
        tail.xRot = -0.2f + Mth.sin(t * 0.2f) * 0.1f;
        leftLeg.xRot = Mth.cos(walk) * 0.8f * amt;
        rightLeg.xRot = -Mth.cos(walk) * 0.8f * amt;
        body.y = 24f - 6f + Mth.sin(t * 0.45f) * 0.4f;

    }
}
