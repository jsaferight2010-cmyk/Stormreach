    @Override
    public void setupAnim(RigState s) {
        super.setupAnim(s);
        float t = s.ageInTicks;
        float moveW = Rig.ease(Math.min(1f, s.walkAnimationSpeed * 2.2f)), idleW = 1f - moveW;
        float air = s.air, ground = 1f - air, swim = s.isInWater ? 1f : 0f, dry = 1f - swim;
        float turn = Mth.clamp(s.turn, -12f, 12f);
        { float w = 1f; float ph = t / 7f + s.seed;
          if (w > 0.002f) {
            core.x += Keys.loop(K1, ph) * w;
            core.z += Keys.loop(K2, ph) * w;
            { float d = Keys.loop(K3, ph) * w; core.xScale += d; core.yScale += d; core.zScale += d; }
        } }
        { float w = 1f; float ph = t / 40f + s.seed;
          if (w > 0.002f) {
            core.y += Keys.loop(K4, ph) * w;
        } }
        { float ph = Rig.pulse(s.attackAge, 10f);
          if (ph >= 0 && s.attackKind == AnimPulse.ATTACK) {
            { float d = Keys.once(K5, ph) * 1f; core.xScale += d; core.yScale += d; core.zScale += d; }
        } }
        { float ph = Rig.pulse(s.attackAge, 10f);
          if (ph >= 0 && s.attackKind == AnimPulse.CAST) {
            { float d = Keys.once(K6, ph) * 1f; core.xScale += d; core.yScale += d; core.zScale += d; }
        } }
        { float ph = Rig.pulse(s.hurtAge, 10f);
          if (ph >= 0) {
            { float d = Keys.once(K7, ph) * 1f; core.xScale += d; core.yScale += d; core.zScale += d; }
        } }
        core.yRot += t * 0.2f;
        arc0.yRot += t * 0.6f; arc1.xRot += t * 0.5f; arc2.zRot += t * 0.7f;

    }
