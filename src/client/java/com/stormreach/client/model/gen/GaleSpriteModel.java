    @Override
    public void setupAnim(RigState s) {
        super.setupAnim(s);
        float t = s.ageInTicks;
        float moveW = Rig.ease(Math.min(1f, s.walkAnimationSpeed * 2.2f)), idleW = 1f - moveW;
        float air = s.air, ground = 1f - air, swim = s.isInWater ? 1f : 0f, dry = 1f - swim;
        float turn = Mth.clamp(s.turn, -12f, 12f);
        { float w = 1f; float ph = t / 3f + s.seed;
          if (w > 0.002f) {
            leftWingBack.zRot += Rig.DEG * Keys.loop(K1, ph) * w;
            leftWingFront.zRot += Rig.DEG * Keys.loop(K2, ph) * w;
            rightWingBack.zRot += Rig.DEG * Keys.loop(K3, ph) * w;
            rightWingFront.zRot += Rig.DEG * Keys.loop(K4, ph) * w;
        } }
        { float w = 1f; float ph = t / 26f + s.seed;
          if (w > 0.002f) {
            body.y += Keys.loop(K5, ph) * w;
            leftAntenna.zRot += Rig.DEG * Keys.loop(K6, ph) * w;
            leftArm.zRot += Rig.DEG * Keys.loop(K7, ph) * w;
            rightAntenna.zRot += Rig.DEG * Keys.loop(K8, ph) * w;
            rightArm.zRot += Rig.DEG * Keys.loop(K9, ph) * w;
            tail0.xRot += Rig.DEG * Keys.loop(K10, ph) * w;
            tail0.zRot += Rig.DEG * Keys.loop(K11, ph) * w;
            tail1.xRot += Rig.DEG * Keys.loop(K12, ph) * w;
            tail2.xRot += Rig.DEG * Keys.loop(K13, ph) * w;
        } }
        { float w = 1f; float ph = Rig.fidget(t, s.seed, 160f, 20f);
          if (ph >= 0 && w > 0.002f) {
            body.y += Keys.once(K14, ph) * w;
            body.xRot += Rig.DEG * Keys.once(K15, ph) * w;
        } }
        { float ph = Rig.pulse(s.hurtAge, 10f);
          if (ph >= 0) {
            body.z += Keys.once(K16, ph) * 1f;
            body.xRot += Rig.DEG * Keys.once(K17, ph) * 1f;
            head.xRot += Rig.DEG * Keys.once(K18, ph) * 1f;
            head.zRot += Rig.DEG * Keys.once(K19, ph) * 1f;
        } }
        head.yRot += s.yRot * Rig.DEG * 1f; head.xRot += s.xRot * Rig.DEG * 1f;

    }
