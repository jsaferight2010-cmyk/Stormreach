    @Override
    public void setupAnim(RigState s) {
        super.setupAnim(s);
        float t = s.ageInTicks;
        float moveW = Rig.ease(Math.min(1f, s.walkAnimationSpeed * 2.2f)), idleW = 1f - moveW;
        float air = s.air, ground = 1f - air, swim = s.isInWater ? 1f : 0f, dry = 1f - swim;
        float turn = Mth.clamp(s.turn, -12f, 12f);
        { float w = 1f; float ph = t / 16f + s.seed;
          if (w > 0.002f) {
            head.yRot += Rig.DEG * Keys.loop(K1, ph) * w;
            seg0.yRot += Rig.DEG * Keys.loop(K2, ph) * w;
            seg1.yRot += Rig.DEG * Keys.loop(K3, ph) * w;
            seg2.yRot += Rig.DEG * Keys.loop(K4, ph) * w;
            seg3.yRot += Rig.DEG * Keys.loop(K5, ph) * w;
            seg4.yRot += Rig.DEG * Keys.loop(K6, ph) * w;
            seg5.yRot += Rig.DEG * Keys.loop(K7, ph) * w;
            seg6.yRot += Rig.DEG * Keys.loop(K8, ph) * w;
        } }
        { float w = 1f; float ph = Rig.fidget(t, s.seed, 80f, 10f);
          if (ph >= 0 && w > 0.002f) {
            jaw.xRot += Rig.DEG * Keys.once(K9, ph) * w;
        } }
        { float ph = Rig.pulse(s.attackAge, 10f);
          if (ph >= 0 && s.attackKind == AnimPulse.ATTACK) {
            head.z += Keys.once(K10, ph) * 1f;
            jaw.xRot += Rig.DEG * Keys.once(K11, ph) * 1f;
            seg0.yRot += Rig.DEG * Keys.once(K12, ph) * 1f;
        } }
        { float ph = Rig.pulse(s.hurtAge, 10f);
          if (ph >= 0) {
            head.z += Keys.once(K13, ph) * 1f;
            head.xRot += Rig.DEG * Keys.once(K14, ph) * 1f;
        } }

    }
