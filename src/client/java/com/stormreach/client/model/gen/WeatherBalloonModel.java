/**
 * The Weather Balloon: a latex balloon that swells as it climbs, trailing a radiosonde with a blinking light on a swaying cord.
 * Generated by tools/mobmodels.py (texture textures/entity/weather_balloon.png, 128x64 units at 4x). Don't edit.
 */
@SuppressWarnings("unused")
public class WeatherBalloonModel extends EntityModel<RigState> {
    private static final float[] K1 = {0.25f, 3f, 0.75f, -3f};
    private static final float[] K2 = {0f, 4f, 0.5f, -4f};
    private static final float[] K3 = {0f, 0f, 0.25f, 20f, 0.5f, 0f, 0.75f, -20f};
    private static final float[] K4 = {0.3f, -10f, 0.8f, 10f};
    private static final float[] K5 = {0.1f, -6f, 0.6f, 6f};
    private static final float[] K6 = {0.2f, -8f, 0.7f, 8f};

    final ModelPart balloon;
    final ModelPart string;
    final ModelPart string2;
    final ModelPart sonde;

    public WeatherBalloonModel(ModelPart root) {
        super(root);
        balloon = root.getChild("balloon");
        string = root.getChild("balloon").getChild("string");
        string2 = root.getChild("balloon").getChild("string").getChild("string2");
        sonde = root.getChild("balloon").getChild("string").getChild("string2").getChild("sonde");
    }

    public static LayerDefinition createBodyLayer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        PartDefinition p1 = root.addOrReplaceChild("balloon", CubeListBuilder.create().texOffs(0, 0).addBox(-6f, -6f, -6f, 12, 12, 12).texOffs(0, 24).addBox(-7f, -4f, -4f, 14, 8, 8).texOffs(48, 0).addBox(-4f, -4f, -7f, 8, 8, 14).texOffs(92, 0).addBox(-4f, -7f, -4f, 8, 14, 8).texOffs(52, 24).addBox(-2f, 6.5f, -2f, 4, 3, 4).texOffs(78, 24).addBox(-1f, 9f, -1f, 2, 2, 2), PartPose.offset(0f, -6f, 0f));
        PartDefinition p2 = p1.addOrReplaceChild("string", CubeListBuilder.create().texOffs(44, 24).addBox(-0.5f, 0f, -0.5f, 1, 8, 1), PartPose.offset(0f, 11f, 0f));
        PartDefinition p3 = p2.addOrReplaceChild("string2", CubeListBuilder.create().texOffs(48, 24).addBox(-0.5f, 0f, -0.5f, 1, 7, 1), PartPose.offset(0f, 8f, 0f));
        PartDefinition p4 = p3.addOrReplaceChild("sonde", CubeListBuilder.create().texOffs(68, 24).addBox(-1.5f, 0f, -1f, 3, 4, 2).texOffs(86, 24).addBox(-0.5f, 4f, -0.5f, 1, 3, 1).texOffs(90, 24).addBox(-1.2f, 1f, -1.3f, 2, 1, 1), PartPose.offset(0f, 7f, 0f));
        return LayerDefinition.create(mesh, 128, 64);
    }

    @Override
    public void setupAnim(RigState s) {
        super.setupAnim(s);
        float t = s.ageInTicks;
        float moveW = Rig.ease(Math.min(1f, s.walkAnimationSpeed * 2.2f)), idleW = 1f - moveW;
        float air = s.air, ground = 1f - air, swim = s.isInWater ? 1f : 0f, dry = 1f - swim;
        float turn = Mth.clamp(s.turn, -12f, 12f);
        { float w = 1f; float ph = t / 50f + s.seed;
          if (w > 0.002f) {
            balloon.xRot += Rig.DEG * Keys.loop(K1, ph) * w;
            balloon.zRot += Rig.DEG * Keys.loop(K2, ph) * w;
            sonde.yRot += Rig.DEG * Keys.loop(K3, ph) * w;
            sonde.zRot += Rig.DEG * Keys.loop(K4, ph) * w;
            string.zRot += Rig.DEG * Keys.loop(K5, ph) * w;
            string2.zRot += Rig.DEG * Keys.loop(K6, ph) * w;
        } }
        float g = Math.min(1f, s.ageInTicks / 600f) * 0.7f;
        balloon.xScale += g; balloon.yScale += g; balloon.zScale += g;

    }
}
