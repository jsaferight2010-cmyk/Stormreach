    @Override
    public void setupAnim(RigState s) {
        super.setupAnim(s);
        float t = s.ageInTicks;
        float moveW = Rig.ease(Math.min(1f, s.walkAnimationSpeed * 2.2f)), idleW = 1f - moveW;
        float air = s.air, ground = 1f - air, swim = s.isInWater ? 1f : 0f, dry = 1f - swim;
        float turn = Mth.clamp(s.turn, -12f, 12f);
        { float w = 1f; float ph = t / 100f + s.seed;
          if (w > 0.002f) {
            body.y += Keys.loop(K1, ph) * w;
            { float d = Keys.loop(K2, ph) * w; leftTip.xScale += d; leftTip.yScale += d; leftTip.zScale += d; }
            neck.xRot += Rig.DEG * Keys.loop(K3, ph) * w;
            { float d = Keys.loop(K4, ph) * w; rightTip.xScale += d; rightTip.yScale += d; rightTip.zScale += d; }
            tail.xRot += Rig.DEG * Keys.loop(K5, ph) * w;
        } }
        { float w = moveW; float ph = s.walkAnimationPos * 0.13f;
          if (w > 0.002f) {
            body.y += Keys.loop(K6, ph) * w;
            leg0.xRot += Rig.DEG * Keys.loop(K7, ph) * w;
            leg1.xRot += Rig.DEG * Keys.loop(K8, ph) * w;
            leg2.xRot += Rig.DEG * Keys.loop(K9, ph) * w;
            leg3.xRot += Rig.DEG * Keys.loop(K10, ph) * w;
            neck.xRot += Rig.DEG * Keys.loop(K11, ph) * w;
            shin0.xRot += Rig.DEG * Keys.loop(K12, ph) * w;
            shin1.xRot += Rig.DEG * Keys.loop(K13, ph) * w;
            shin2.xRot += Rig.DEG * Keys.loop(K14, ph) * w;
            shin3.xRot += Rig.DEG * Keys.loop(K15, ph) * w;
            tail.xRot += Rig.DEG * Keys.loop(K16, ph) * w;
        } }
        { float w = idleW; float ph = Rig.fidget(t, s.seed, 260f, 80f);
          if (ph >= 0 && w > 0.002f) {
            head.xRot += Rig.DEG * Keys.once(K17, ph) * w;
            jaw.xRot += Rig.DEG * Keys.once(K18, ph) * w;
            neck.xRot += Rig.DEG * Keys.once(K19, ph) * w;
        } }
        { float w = idleW; float ph = Rig.fidget(t, s.seed, 70f, 12f);
          if (ph >= 0 && w > 0.002f) {
            leftEar.zRot += Rig.DEG * Keys.once(K20, ph) * w;
        } }
        { float w = idleW; float ph = Rig.fidget(t, s.seed, 90f, 14f);
          if (ph >= 0 && w > 0.002f) {
            rightEar.zRot += Rig.DEG * Keys.once(K21, ph) * w;
            tail.xRot += Rig.DEG * Keys.once(K22, ph) * w;
        } }
        { float ph = Rig.pulse(s.hurtAge, 10f);
          if (ph >= 0) {
            body.z += Keys.once(K23, ph) * 1f;
            body.xRot += Rig.DEG * Keys.once(K24, ph) * 1f;
            head.xRot += Rig.DEG * Keys.once(K25, ph) * 1f;
            head.zRot += Rig.DEG * Keys.once(K26, ph) * 1f;
        } }
        neck.yRot += s.yRot * Rig.DEG * 0.4f; neck.xRot += s.xRot * Rig.DEG * 0.3f;
        head.yRot += s.yRot * Rig.DEG * 0.6f; head.xRot += s.xRot * Rig.DEG * 0.7f;
        neck.yRot -= turn * 0.02f;

    }
